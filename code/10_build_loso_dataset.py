"""Build a leave-one-scenario-out (LOSO) generalization split.

Diagnostic finding (see revision notes): CERT r4.2's malicious HTTP content is generated
from a small closed vocabulary per "dense-needle" scenario instance (r4.2-1 = WikiLeaks/
espionage jargon, 69 rows/30 users; r4.2-2 = job-hunting/leaving-company jargon, 3,738
rows/30 users; r4.2-3 = keylogger/hacking-tool jargon, 53 rows/10 users). A user-grouped
split alone does not de-saturate the benchmark (verified: TF-IDF and even purely structural
metadata both still exceed 99.5% accuracy) because every malicious scenario is generated by
the same kind of small-vocabulary word-repetition process, structurally unlike natural
benign prose, regardless of which specific words are used. The only mechanistic fix is to
hold out an entire scenario's vocabulary/theme from training, so the task actually tests
generalization to a previously unseen insider-threat theme.

Protocol: train/val on scenarios r4.2-2 + r4.2-3 (grouped by user, 85/15), test on the
entirely held-out scenario r4.2-1 (WikiLeaks/espionage) -- neither its users nor its
vocabulary are seen during training or validation. Benign rows are grouped-split by user
across train/val/test in the same 70/15/15 proportions as the original protocol.
"""
import json
import os

import pandas as pd
from sklearn.model_selection import GroupShuffleSplit

import importlib.util
spec = importlib.util.spec_from_file_location("build09", os.path.join(os.path.dirname(__file__), "09_build_grouped_dataset.py"))
build09 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build09)

BASE = os.path.dirname(__file__)
OUT = os.path.join(BASE, "..", "data_processed")
RESULTS = os.path.join(BASE, "..", "results")
os.makedirs(RESULTS, exist_ok=True)

HELD_OUT_SCENARIO = "r4.2-1"


def main():
    mal = build09.load_jsonl(os.path.join(OUT, "malicious_http.jsonl"))
    ben = build09.load_jsonl(os.path.join(OUT, "benign_http_sample.jsonl"))

    mal_rows = build09.build_rows(mal, 1)
    for r, raw in zip(mal_rows, mal):
        r["scenario"] = raw["scenario"]
    ben_rows = build09.build_rows(ben, 0)
    for r in ben_rows:
        r["scenario"] = "benign"

    mal_df = pd.DataFrame(mal_rows).drop_duplicates(subset=["text", "label"]).reset_index(drop=True)
    ben_df = pd.DataFrame(ben_rows).drop_duplicates(subset=["text", "label"]).reset_index(drop=True)

    print("malicious rows by scenario:", mal_df["scenario"].value_counts().to_dict())

    mal_test = mal_df[mal_df["scenario"] == HELD_OUT_SCENARIO].reset_index(drop=True)
    mal_trainval = mal_df[mal_df["scenario"] != HELD_OUT_SCENARIO].reset_index(drop=True)

    # sanity: no user overlap between the held-out scenario and the training scenarios
    overlap = set(mal_test["user"]) & set(mal_trainval["user"])
    print("user overlap between held-out scenario and training scenarios (must be 0):", len(overlap))

    gss = GroupShuffleSplit(n_splits=1, test_size=0.15, random_state=42)
    tr_idx, va_idx = next(gss.split(mal_trainval, groups=mal_trainval["user"]))
    mal_train = mal_trainval.iloc[tr_idx].reset_index(drop=True)
    mal_val = mal_trainval.iloc[va_idx].reset_index(drop=True)

    ben_train, ben_val, ben_test = build09.grouped_split(ben_df, seed=42, test_frac=0.30, second_frac=0.5)

    train_df = pd.concat([mal_train, ben_train], ignore_index=True).sample(frac=1, random_state=42).reset_index(drop=True)
    val_df = pd.concat([mal_val, ben_val], ignore_index=True).sample(frac=1, random_state=42).reset_index(drop=True)
    test_df = pd.concat([mal_test, ben_test], ignore_index=True).sample(frac=1, random_state=42).reset_index(drop=True)

    sizes = {"train": len(train_df), "val": len(val_df), "test": len(test_df)}
    rates = {
        "train": float(train_df["label"].mean()),
        "val": float(val_df["label"].mean()),
        "test": float(test_df["label"].mean()),
    }
    print("LOSO split sizes:", sizes, "positive rates:", rates)

    # standardize numeric metadata using TRAIN statistics only
    num_cols = ["content_len", "content_word_count", "digit_ratio", "url_len", "url_path_depth", "hour", "dow"]
    mu = train_df[num_cols].mean()
    sigma = train_df[num_cols].std().replace(0, 1.0)
    for split_df in (train_df, val_df, test_df):
        for c in num_cols:
            split_df[c + "_z"] = (split_df[c] - mu[c]) / sigma[c]

    tld_cats = sorted(train_df["tld"].unique().tolist())
    for split_df in (train_df, val_df, test_df):
        for cat in tld_cats:
            split_df[f"tld_{cat}"] = (split_df["tld"] == cat).astype(float)

    meta_cols = [c + "_z" for c in num_cols] + [f"tld_{c}" for c in tld_cats]

    for name, split_df in [("train", train_df), ("val", val_df), ("test", test_df)]:
        keep = ["text", "label", "user", "scenario"] + meta_cols
        split_df[keep].to_csv(os.path.join(OUT, f"{name}_loso.csv"), index=False)

    meta = {
        "held_out_scenario": HELD_OUT_SCENARIO,
        "meta_cols": meta_cols,
        "tld_categories": tld_cats,
        "sizes": sizes,
        "positive_rates": rates,
        "user_overlap_test_vs_train": int(len(overlap)),
        "scenario_counts": mal_df["scenario"].value_counts().to_dict(),
    }
    with open(os.path.join(RESULTS, "loso_split_meta.json"), "w") as fh:
        json.dump(meta, fh, indent=2)
    print("saved LOSO split. meta_cols:", meta_cols)


if __name__ == "__main__":
    main()
